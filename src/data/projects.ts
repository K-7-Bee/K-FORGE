import type { ProjectDef, ProjectMilestone } from './types';

function ms(
  id: string,
  title: string,
  partial: Omit<ProjectMilestone, 'id' | 'title' | 'xp'> & { xp?: number },
): ProjectMilestone {
  return { id, title, xp: partial.xp ?? 100, ...partial };
}

/** Mini-projects use three standard milestones: build, verify, document. */
function miniMilestones(build: string[], test: string[], metric?: ProjectMilestone['metric']): ProjectMilestone[] {
  return [
    ms('build', 'Build and program', {
      knowledge: [], components: [], wiring: '', tasks: build, testing: [], xp: 0,
      checklist: ['Circuit built from your own schematic', 'Firmware compiles with no warnings', 'Code committed to GitHub'],
    }),
    ms('verify', 'Test and measure', {
      knowledge: [], components: [], wiring: '', tasks: test, testing: test, xp: 0, metric,
      checklist: ['Test procedure executed', 'Measured results recorded in Testing records', 'At least one failure case tried on purpose'],
    }),
    ms('document', 'Document', {
      knowledge: [], components: [], wiring: '', tasks: ['Write a README: summary, photo, schematic, how to build, test results, limitations'], testing: [], xp: 0,
      checklist: ['README written', 'Photo or video uploaded', 'You can explain every line without notes'],
    }),
  ];
}

